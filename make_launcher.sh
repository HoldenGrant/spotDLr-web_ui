#!/bin/bash
# Builds spotDLr.app: double-click it to start the server (if it isn't running) and open
# spotDLr in its own window, with no Terminal and nothing to type.
#
#   ./make_launcher.sh                # installs to /Applications (or ~/Applications)
#   ./make_launcher.sh ~/Desktop      # or anywhere else
#
# Re-run it if you move this project folder: the app remembers where the project lives.

set -euo pipefail
cd "$(dirname "$0")"
REPO="$(pwd)"

DEST="${1:-/Applications}"
if [ ! -w "$DEST" ]; then
    DEST="$HOME/Applications"
fi
mkdir -p "$DEST"
APP="$DEST/spotDLr.app"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ---------- icon: SVG → 1024 px PNG → .icns ----------
echo "Rendering icon..."
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
if [ -x "$CHROME" ]; then
    "$CHROME" --headless=new --disable-gpu --hide-scrollbars --default-background-color=00000000 \
        --user-data-dir="$WORK/chrome" --window-size=1024,1024 \
        --screenshot="$WORK/icon.png" "file://$REPO/launcher/icon.svg" >/dev/null 2>&1
else
    qlmanage -t -s 1024 -o "$WORK" "$REPO/launcher/icon.svg" >/dev/null 2>&1
    mv "$WORK/icon.svg.png" "$WORK/icon.png"
fi
ICONSET="$WORK/spotDLr.iconset"
mkdir -p "$ICONSET"
for size in 16 32 128 256 512; do
    sips -z $size $size "$WORK/icon.png" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
    sips -z $((size * 2)) $((size * 2)) "$WORK/icon.png" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$WORK/spotDLr.icns"

# ---------- bundle ----------
echo "Building $APP..."
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$WORK/spotDLr.icns" "$APP/Contents/Resources/spotDLr.icns"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>                <string>spotDLr</string>
    <key>CFBundleDisplayName</key>         <string>spotDLr</string>
    <key>CFBundleIdentifier</key>          <string>com.holdengrant.spotdlr.launcher</string>
    <key>CFBundleExecutable</key>          <string>spotDLr</string>
    <key>CFBundleIconFile</key>            <string>spotDLr</string>
    <key>CFBundlePackageType</key>         <string>APPL</string>
    <key>CFBundleShortVersionString</key>  <string>1.0</string>
    <key>LSMinimumSystemVersion</key>      <string>11.0</string>
    <!-- A launcher, not a windowed app: no Dock icon of its own while it runs (the window is Chrome's) -->
    <key>LSUIElement</key>                 <true/>
</dict>
</plist>
PLIST

# Apps opened from Finder get a bare PATH (/usr/bin:/bin:…), which hides Python 3.13, Homebrew's
# ffmpeg and Node (yt-dlp needs Node, or YouTube answers 403). Bake in this Terminal's PATH.
{
    echo '#!/bin/bash'
    echo '# spotDLr launcher, generated by make_launcher.sh. Re-run that script if the project moves.'
    printf 'REPO=%q\n' "$REPO"
    printf 'export PATH=%q\n' "$PATH:/opt/homebrew/bin:/usr/local/bin"
    cat <<'LAUNCHER'
# A script-only app has no native binary for macOS to inspect, so on Apple Silicon it starts under
# Rosetta (x86_64), and every child inherits that: Python then can't load the venv's arm64 libraries.
# Restart natively.
if [ "$(sysctl -n hw.optional.arm64 2>/dev/null)" = "1" ] && [ "$(uname -m)" != "arm64" ]; then
    exec arch -arm64 /bin/bash "$0" "$@"
fi

PORT=8000
URL="http://localhost:$PORT"
LOG="$HOME/Library/Logs/spotDLr.log"

notify() { osascript -e "display notification \"$1\" with title \"spotDLr\"" >/dev/null 2>&1 || true; }
fail() {
    osascript -e "display alert \"spotDLr couldn't start\" message \"$1\" as critical" >/dev/null 2>&1 || true
    exit 1
}
# "Is spotDLr answering?", not just "is the port open": another app could hold port 8000
is_spotdlr() { curl -s --max-time 2 "$URL/api/status/init" 2>/dev/null | grep -q '"search_source"'; }

[ -x "$REPO/run.sh" ] || fail "The project folder isn't at $REPO anymore. Open Terminal in its new location and run ./make_launcher.sh again."

if ! is_spotdlr; then
    if lsof -nP -iTCP:$PORT -sTCP:LISTEN >/dev/null 2>&1; then
        fail "Port $PORT is being used by another app, so spotDLr can't start. Quit that app and try again."
    fi
    # Keep the log from growing forever
    if [ -f "$LOG" ] && [ "$(stat -f %z "$LOG")" -gt 5000000 ]; then mv "$LOG" "$LOG.old"; fi
    echo "=== $(date '+%Y-%m-%d %H:%M:%S') starting spotDLr" >> "$LOG"
    # nohup: the server keeps running after this launcher exits (so the next launch is instant)
    SPOTDLR_NO_BROWSER=1 nohup "$REPO/run.sh" >> "$LOG" 2>&1 < /dev/null &
    SERVER_PID=$!
    STARTED=$(date +%s)
    NOTIFIED=0
    until is_spotdlr; do
        if ! kill -0 "$SERVER_PID" 2>/dev/null; then
            fail "The server stopped while starting. Details are in ~/Library/Logs/spotDLr.log"
        fi
        ELAPSED=$(( $(date +%s) - STARTED ))
        if [ "$ELAPSED" -ge 4 ] && [ "$NOTIFIED" = 0 ]; then
            notify "Starting… The first launch installs what it needs and can take a minute."
            NOTIFIED=1
        fi
        [ "$ELAPSED" -gt 300 ] && fail "Starting took more than 5 minutes. Details are in ~/Library/Logs/spotDLr.log"
        sleep 0.5
    done
fi

# Its own window: a Chromium browser in app mode (no tabs, no address bar).
# Run the binary directly: "open -a … --args" drops the arguments when the browser is already open.
for BROWSER in "Google Chrome" "Microsoft Edge" "Brave Browser" "Chromium"; do
    for BASE in "/Applications" "$HOME/Applications"; do
        BIN="$BASE/$BROWSER.app/Contents/MacOS/$BROWSER"
        if [ -x "$BIN" ]; then
            "$BIN" --app="$URL" >/dev/null 2>&1 &
            exit 0
        fi
    done
done
open "$URL"  # no Chromium browser: fall back to a normal tab in the default browser
LAUNCHER
} > "$APP/Contents/MacOS/spotDLr"
chmod +x "$APP/Contents/MacOS/spotDLr"

touch "$APP"  # nudge Finder to pick up the new icon
echo "Done: $APP"
echo "Open it from Launchpad or Applications, and drag it to the Dock to keep it there."
